defmodule PrimaAuth0Ex.Auth0Credentials do
  @moduledoc """
  Credentials to access Auth0.

  For `private_key_jwt`, `private_key` is PEM key material used to sign the
  assertion; it is not copied into a JWT field. `private_key_id` maps to the
  optional JWT `kid` header, and `signing_algorithm` maps to the JWT `alg`
  header. These are library config names, not Auth0 field names.

  The assertion's `iss` and `sub` come from `client_id`, while `aud` comes from
  the OpenID issuer. `iat`, `exp`, and `jti` are generated by the library.
  The RS256 default is an assumption until the requesting team confirms the
  algorithm configured for its Auth0 credential.
  """

  alias PrimaAuth0Ex.Config

  @type signing_algorithm :: :rs256 | :rs384 | :ps256

  @type t :: %__MODULE__{
          client: atom(),
          base_url: String.t(),
          client_id: String.t(),
          client_secret: String.t() | nil,
          authentication_method: :client_secret | :private_key_jwt,
          private_key: String.t() | nil,
          private_key_id: String.t() | nil,
          signing_algorithm: signing_algorithm()
        }
  @enforce_keys [:client, :base_url, :client_id, :client_secret]
  defstruct [
    :client,
    :base_url,
    :client_id,
    :client_secret,
    authentication_method: :client_secret,
    private_key: nil,
    private_key_id: nil,
    # Assumption pending requester confirmation: the Auth0 credential uses RS256.
    signing_algorithm: :rs256
  ]

  @spec from_env(atom()) :: __MODULE__.t()
  def from_env(name \\ :default_client)

  def from_env(:default_client) do
    client = Config.default_client()

    %__MODULE__{
      client: :default_client,
      base_url: Keyword.get(client, :auth0_base_url),
      client_id: Keyword.get(client, :client_id),
      client_secret: Keyword.get(client, :client_secret),
      authentication_method: Keyword.get(client, :authentication_method, :client_secret),
      private_key: Keyword.get(client, :private_key),
      private_key_id: Keyword.get(client, :private_key_id),
      signing_algorithm: Keyword.get(client, :signing_algorithm, :rs256)
    }
  end

  def from_env(name) do
    client = Config.clients(name)

    %__MODULE__{
      client: name,
      base_url: Keyword.get(client, :auth0_base_url),
      client_id: Keyword.get(client, :client_id),
      client_secret: Keyword.get(client, :client_secret),
      authentication_method: Keyword.get(client, :authentication_method, :client_secret),
      private_key: Keyword.get(client, :private_key),
      private_key_id: Keyword.get(client, :private_key_id),
      signing_algorithm: Keyword.get(client, :signing_algorithm, :rs256)
    }
  end
end
